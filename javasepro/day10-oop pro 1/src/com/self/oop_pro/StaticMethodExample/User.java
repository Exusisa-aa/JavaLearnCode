package com.self.oop_pro.StaticMethodExample;

public class User {
    private String nmae;

    public User(String nmae) {
        this.nmae = nmae;
    }

    public User() {
    }

    public String getNmae() {
        return nmae;
    }

    public void setNmae(String nmae) {
        this.nmae = nmae;
    }
}
